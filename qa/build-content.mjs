// Bundle content/extra/*.js into content/extra.js and content/new/*.js into content/towns-new.js,
// which are what index.html loads.  --check: fail if a bundle is out of date.
import fs from 'node:fs';
const jobs = [['content/extra', 'content/extra.js', 'longer levels: window.extendLevel calls'], ['content/new', 'content/towns-new.js', 'new towns: levels 51 and up']];
let stale = 0;
for (const [dir, out, what] of jobs) {
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort() : [];
  const body = `// GENERATED by qa/build-content.mjs from ${dir}/*.js (${what}). Edit the source files, then run npm run build:content.\n` + files.map(f => `\n// ---- ${dir}/${f}\n` + fs.readFileSync(`${dir}/${f}`, 'utf8').trimEnd() + '\n').join('');
  if (process.argv.includes('--check')) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) { console.log(`STALE ${out}: run npm run build:content`); stale++; } }
  else { fs.writeFileSync(out, body); console.log(`${out}: ${files.length} files`); }
}
process.exit(stale ? 1 : 0);
